// 3270 buffer addresses. Two bytes either way: 12-bit addresses put six bits
// in each byte through a code table (the high bits are never 00), and 14-bit
// addresses are binary with the high two bits 00.

/** The 64 bytes that carry six address bits each. */
export const ADDRESS_CODES = [
  0x40, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7, 0xc8, 0xc9, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
  0x50, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6, 0xd7, 0xd8, 0xd9, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f,
  0x60, 0x61, 0xe2, 0xe3, 0xe4, 0xe5, 0xe6, 0xe7, 0xe8, 0xe9, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f,
  0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0x7a, 0x7b, 0x7c, 0x7d, 0x7e, 0x7f,
] as const;

export function decodeAddress(b1: number, b2: number): number {
  if ((b1 & 0xc0) === 0) return ((b1 & 0x3f) << 8) | b2;
  return ((b1 & 0x3f) << 6) | (b2 & 0x3f);
}

/** 12-bit coded for buffers up to 4096 positions, as hosts expect; 14-bit above that. */
export function encodeAddress(address: number, bufferSize: number): [number, number] {
  if (bufferSize > 4096) return [(address >> 8) & 0x3f, address & 0xff];
  return [ADDRESS_CODES[(address >> 6) & 0x3f]!, ADDRESS_CODES[address & 0x3f]!];
}
